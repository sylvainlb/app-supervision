// build-features.mjs — v2: NO business component packaged in the app, everything goes
// through the CDN (bundle + SRI). Builds one ESM bundle per base feature (route slug):
//
//   public/features-dist/<slug>.js      ← self-contained bundle (lit + boilerplate included)
//   public/features-dist/manifest.json  ← { slug: { tag, cdn_url, sri (sha384-<b64>), bytes } }
//   ../app-supervision-backend/sql/131_base_features_v2.sql ← UPDATE app.features (v2 columns)
//
// The "store" component (app-store/app-menu) stays packaged: it is the mechanism that
// installs the others (bootstrap). The 12 business batches are built by
// app-features/scripts/build.mjs (seed 130).
//
// Usage: node scripts/build-features.mjs   (from app-supervision/)
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const OUT = join(ROOT, 'public/features-dist');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const orbit = JSON.parse(readFileSync(join(ROOT, 'orbit.json'), 'utf8'));

// slug → route tags (components + sections), store excluded (packaged, bootstrap)
const entries = {};
for (const r of orbit.routes) {
  if (r.dynamic || r.name === 'store') continue;
  if (r.name === 'ticket-new' || r.name === 'ticket-detail') continue; // sub-routes of tickets (in the tickets bundle)
  const comps = [...new Set([...(r.components ?? []), ...(r.sections ?? []).flatMap((s) => s.components ?? [])])];
  entries[r.name] = comps;
}

mkdirSync(OUT, { recursive: true });
const manifest = { package: '@facis/app-supervision', version: pkg.version, features: {} };
const updates = [];

for (const [slug, comps] of Object.entries(entries)) {
  const entry = join(ROOT, 'components/features-entries', slug + '.js');
  const outfile = join(OUT, slug + '.js');
  await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    logLevel: 'silent',
    alias: {
      // full lit tree (app-store/node_modules) — the local node_modules may be partial
      lit: join(ROOT, '../app-store/node_modules/lit'),
      '@lit/task': join(ROOT, '../app-store/node_modules/@lit/task'),
      '@lit/reactive-element': join(ROOT, '../app-store/node_modules/@lit/reactive-element'),
      'lit-html': join(ROOT, '../app-store/node_modules/lit-html'),
      'lit-element': join(ROOT, '../app-store/node_modules/lit-element'),
    },
  });
  const bytes = readFileSync(outfile);
  const sri = 'sha384-' + createHash('sha384').update(bytes).digest('base64');
  const tag = comps[0];
  const cdnUrl = `/features-dist/${slug}.js`;
  manifest.features[slug] = { tag, cdn_url: cdnUrl, sri, bytes: bytes.length, components: comps };
  updates.push(
    `UPDATE app.features SET npm_package = '@facis/app-supervision', version = '${pkg.version}', ` +
    `cdn_url = '${cdnUrl}', sri = '${sri}', tag = '${tag}' WHERE slug = '${slug}' AND deleted_at IS NULL;`);
  console.log(`build ${slug} → public/features-dist/${slug}.js (${bytes.length} bytes, tags: ${comps.join(',')}, ${sri.slice(0, 20)}…)`);
}

writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2));

const sql = `-- ============================================================================
-- App store v2 — 131_base_features_v2.sql: the BASE features become
-- DISTANT (CDN + SRI) — no more business component packaged in the app.
-- Generated by app-supervision/scripts/build-features.mjs (sri = real sha384 of
-- the bundle public/features-dist/<slug>.js). The store component (app-store/app-menu)
-- stays packaged: it is the install mechanism (bootstrap).
-- Idempotent — replayed at boot by deploy-local.sh.
-- ============================================================================

${updates.join('\n')}
`;
const sqlPath = join(ROOT, '../app-supervision-backend/sql/131_base_features_v2.sql');
writeFileSync(sqlPath, sql);
console.log(`seed SQL generated → ${sqlPath} (${updates.length} features)`);
